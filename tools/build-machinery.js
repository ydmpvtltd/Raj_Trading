#!/usr/bin/env node
/*
 * Generates the static /machinery/ pages, sitemap.xml and robots.txt from
 * data/harvesters.js, so specs live in one place but are still readable by
 * search engines without JavaScript. Then builds css/tailwind.css, the
 * precompiled Tailwind stylesheet used by every page.
 *
 * Run after editing data/harvesters.js, index.html or any page markup:
 *   node tools/build-machinery.js
 *
 * Needs Node and internet the first time (npx downloads Tailwind 3.4.16).
 */
const fs = require('fs');
const { execSync } = require('child_process');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const D = require(path.join(ROOT, 'data/harvesters.js'));
const R = require(path.join(ROOT, 'js/machinery-render.js'));
const { esc, fmt } = R;

const SITE = D.siteUrl;
const BUSINESS_ID = SITE; // matches the @id of the LocalBusiness on the home page

function jsonLd(data) {
  // Escape "<" so the JSON can never close the script tag early
  return `<script type="application/ld+json">\n${JSON.stringify(data, null, 2).replace(/</g, '\\u003c')}\n  </script>`;
}

function businessNode() {
  const b = D.business;
  return {
    '@type': 'LocalBusiness',
    '@id': BUSINESS_ID,
    name: b.name,
    url: SITE,
    image: `${SITE}rajlogo.jpeg`,
    telephone: b.phones[0].tel,
    address: {
      '@type': 'PostalAddress',
      streetAddress: b.streetAddress,
      addressLocality: b.addressLocality,
      addressRegion: b.addressRegion,
      postalCode: b.postalCode,
      addressCountry: 'IN',
    },
  };
}

function breadcrumbNode(items) {
  return {
    '@type': 'BreadcrumbList',
    itemListElement: items.map((item, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: item.name,
      ...(item.url ? { item: item.url } : {}),
    })),
  };
}

function page({ title, description, canonical, image, imageAlt, ogType = 'website', schema, bodyAttrs, main, stickyText, selectedModel }) {
  return `<!DOCTYPE html>
<!-- Generated by tools/build-machinery.js from data/harvesters.js. Edit the data file and re-run instead of editing this page. -->
<html lang="${D.lang}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  <meta name="robots" content="index, follow">
  <link rel="canonical" href="${canonical}">

  <!-- Open Graph / Social Sharing -->
  <meta property="og:type" content="${ogType}">
  <meta property="og:site_name" content="${esc(D.business.name)}">
  <meta property="og:locale" content="en_IN">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:url" content="${canonical}">
  <meta property="og:image" content="${image}">
  <meta property="og:image:alt" content="${esc(imageAlt)}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(title)}">
  <meta name="twitter:description" content="${esc(description)}">
  <meta name="twitter:image" content="${image}">

  <link rel="icon" type="image/jpeg" href="../rajlogo.jpeg">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&display=swap">
  <link rel="stylesheet" href="../css/tailwind.css">
  <link rel="stylesheet" href="../css/machinery.css">

  ${jsonLd({ '@context': 'https://schema.org', '@graph': schema })}
</head>
<body ${bodyAttrs} data-root="../" class="bg-white font-sans text-gray-800 antialiased pb-16 md:pb-0">
  <a href="#main" class="sr-only focus:not-sr-only focus:fixed focus:top-2 focus:left-2 focus:z-50 focus:bg-white focus:px-4 focus:py-2 focus:rounded-lg focus:shadow-lg">Skip to content</a>

  <div id="rt-header" class="contents">
  ${R.header(D, { root: '../', active: 'machinery' })}
  </div>

  <main id="main">
    ${main}
  </main>

  <div id="rt-footer" class="contents">
  ${R.footer(D, { root: '../' })}
  </div>

  <div id="rt-sticky" class="contents">
  ${R.stickyBar(D, { whatsappText: stickyText })}
  </div>

  <div id="rt-dialog" class="contents">
  ${R.demoDialog(D, { selected: selectedModel })}
  </div>

  <script defer src="https://unpkg.com/lucide@0.462.0/dist/umd/lucide.min.js"></script>
  <script defer src="../data/harvesters.js"></script>
  <script defer src="../js/machinery-render.js"></script>
  <script defer src="../js/machinery-page.js"></script>
</body>
</html>
`;
}

function productPage(model) {
  const url = `${SITE}machinery/${model.id}.html`;
  const title = fmt(D.ui.productTitle, { model: model.name });
  const description = fmt(D.ui.productDescription, { model: model.name, type: model.type, summary: model.summary });
  const image = `${SITE}${model.image}`;
  const name = `LOVOL ${model.name} Combine Harvester`;

  const schema = [
    {
      '@type': 'Product',
      '@id': `${url}#product`,
      name,
      description: model.summary,
      image: [image],
      brand: { '@type': 'Brand', name: 'LOVOL' },
      category: 'Combine Harvester',
      model: model.name,
      url,
      sameAs: model.officialPage,
      additionalProperty: D.specs.map(spec => ({
        '@type': 'PropertyValue',
        name: spec.label,
        value: model.specs[spec.key].value,
      })),
      // No price is published, so `offers` is intentionally omitted.
    },
    breadcrumbNode([
      { name: D.ui.breadcrumb.home, url: SITE },
      { name: D.ui.breadcrumb.machinery, url: `${SITE}machinery/` },
      { name: D.ui.breadcrumb.harvesters, url: `${SITE}machinery/#harvesters` },
      { name: model.name },
    ]),
    {
      '@type': 'WebPage',
      '@id': url,
      url,
      name: title,
      about: { '@id': `${url}#product` },
      publisher: { '@id': BUSINESS_ID },
    },
    businessNode(),
  ];

  return page({
    title,
    description,
    canonical: url,
    image,
    imageAlt: model.imageAlt,
    ogType: 'product',
    schema,
    bodyAttrs: `data-page="product" data-model="${model.id}"`,
    main: R.productMain(D, model, { root: '../' }),
    stickyText: fmt(D.ui.whatsapp.price, { model: model.name }),
    selectedModel: model.id,
  });
}

function listingPage() {
  const url = `${SITE}machinery/`;
  const l = D.ui.listing;
  const schema = [
    {
      '@type': 'CollectionPage',
      '@id': url,
      url,
      name: l.title,
      description: l.description,
      publisher: { '@id': BUSINESS_ID },
      mainEntity: {
        '@type': 'ItemList',
        itemListElement: D.models.map((model, i) => ({
          '@type': 'ListItem',
          position: i + 1,
          url: `${SITE}machinery/${model.id}.html`,
          name: `LOVOL ${model.name} Combine Harvester`,
        })),
      },
    },
    breadcrumbNode([
      { name: D.ui.breadcrumb.home, url: SITE },
      { name: D.ui.breadcrumb.machinery },
    ]),
    businessNode(),
  ];

  return page({
    title: l.title,
    description: l.description,
    canonical: url,
    image: `${SITE}${D.models[0].image}`,
    imageAlt: D.models[0].imageAlt,
    schema,
    bodyAttrs: 'data-page="listing"',
    main: R.listingMain(D, { root: '../' }),
    stickyText: D.ui.demo.enquiryMessage,
    selectedModel: '',
  });
}

function sitemap() {
  const today = new Date().toISOString().slice(0, 10);
  const urls = [
    { loc: SITE, priority: '1.0' },
    { loc: `${SITE}machinery/`, priority: '0.9' },
    ...D.models.map(model => ({ loc: `${SITE}machinery/${model.id}.html`, priority: '0.8' })),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-machinery.js -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url>\n    <loc>${u.loc}</loc>\n    <lastmod>${today}</lastmod>\n    <priority>${u.priority}</priority>\n  </url>`).join('\n')}
</urlset>
`;
}

function write(rel, content) {
  const file = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`wrote ${rel}`);
}

D.models.forEach(model => write(`machinery/${model.id}.html`, productPage(model)));
write('machinery/index.html', listingPage());
write('sitemap.xml', sitemap());
write('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${SITE}sitemap.xml\n`);

// Build the stylesheet last, so it picks up every class used in the pages just written
execSync('npx -y tailwindcss@3.4.16 -c tailwind.config.js -i css/tailwind.input.css -o css/tailwind.css --minify', {
  cwd: ROOT,
  stdio: 'inherit',
});
console.log('wrote css/tailwind.css');
